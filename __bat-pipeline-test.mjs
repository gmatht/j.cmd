// ─── bat2js pipeline regression test ───────────────────────────
// Exercises the full batch → JS path the cmd.exe builtin drives:
//
//   .bat → A1 shIR (busybox bat-sh-go frontend) → ESTree
//          (otranspilerl) → JS (estree.js) → executed (sh2.* runtime)
//
// Run: node __bat-pipeline-test.mjs [inline-batch-source]
import { fs } from "./src/fs/index.js";
import { batToJS, runBat } from "./src/bat2js.js";

let failures = 0;
function check(label, got, want) {
  const ok = String(got).trim() === String(want).trim();
  if (!ok) failures++;
  console.log(`${ok ? "PASS" : "FAIL"}  ${label}${ok ? "" : `\n      got:  ${JSON.stringify(String(got).trim())}\n      want: ${JSON.stringify(String(want).trim())}`}`);
}

// ── transpile-only (bat2js mode) ──────────────────────────────
const { js } = await batToJS(fs, "@echo off\necho hello world");
check("batToJS emits the header comment", /Generated by bat2js/.test(js), true);
check("batToJS emits a stdout write for echo", /process\.stdout\.write\("hello world\\n"\)/.test(js), true);

// ── execute ───────────────────────────────────────────────────
let out = "";
let code = await runBat(fs, "echo hello world", { stdout: { write: (s) => { out += s; } } });
check("echo", out, "hello world\n");
check("exit code (success)", code, 0);

// set + %var% + set /a
out = "";
code = await runBat(fs, "set X=5\nset /a N=2+3\necho %X% %N%", { stdout: { write: (s) => { out += s; } } });
check("set / set /a / %var%", out, "5 5\n");

// %errorlevel% maps to the shell's $? — `exit /b 7` then read it
out = "";
code = await runBat(fs, "exit /b 7", { stdout: { write: (s) => { out += s; } } });
check("exit /b 7 exit code", code, 7);

// positional args %1 %2 (the frontend's v1 subset: %1..%9 and %*; %0
// is not wired — see frontends/bat-sh-go/FRONTEND.md)
out = "";
code = await runBat(fs, "echo %1 %2", {
  stdout: { write: (s) => { out += s; } }, args: ["a", "b"], argv0: "demo.bat",
});
check("positionals %1 %2", out, "a b\n");

// if/else + for %%v
out = "";
code = await runBat(fs, "if 1==1 (echo yes) else (echo no)\nfor %%v in (a b c) do echo item %%v", {
  stdout: { write: (s) => { out += s; } },
});
check("if / else / for", out, "yes\nitem a\nitem b\nitem c\n");

// `&` statement separator
out = "";
code = await runBat(fs, "echo one&echo two", { stdout: { write: (s) => { out += s; } } });
check("& statement separator", out, "one\ntwo\n");

// call :label subroutine
out = "";
code = await runBat(fs, "call :greet world\nexit /b 0\n:greet\necho hello %1\ngoto :eof", {
  stdout: { write: (s) => { out += s; } },
});
check("call :label / goto :eof", out, "hello world\n");

// a refused construct errors loudly (REFUSE > GUESS)
let refused = false;
try {
  await runBat(fs, "pause", { stdout: { write: () => {} } });
} catch (e) {
  refused = /unsupported batch command "pause"/.test(e.message);
}
check("unsupported command refuses loudly", refused, true);

// ── env seeding (SH2_ASSUME_NO_ENV fold defeat) ───────────────
// `%HOME%` reads the SHELL's env — the core folds never-written-var
// reads to "", so runBat seeds `set HOME=…` up front.
import { env } from "./src/env.js";
out = "";
code = await runBat(fs, "echo %HOME% %USER%", { stdout: { write: (s) => { out += s; } } });
check("env vars seed (%HOME% %USER%)", out, (env.HOME || "") + " " + (env.USER || "") + "\n");
// a script's own `set NAME=…` still overrides the seed (like real cmd)
out = "";
code = await runBat(fs, "set HOME=/elsewhere\necho %HOME%", { stdout: { write: (s) => { out += s; } } });
check("script set overrides env seed", out, "/elsewhere\n");

// ── template-literal quasi escaping (the otranspilerl v11 fix) ─
// `echo %HOME%\` once emitted `${…}\` — the bare backslash escaped the
// closing backtick → "Unexpected end of input" at eval time.
out = "";
code = await runBat(fs, "echo %HOME%\\", { stdout: { write: (s) => { out += s; } } });
check("trailing backslash after %var%", out, (env.HOME || "") + "\\\n");

console.log(failures === 0 ? "\n✓ bat2js pipeline: all tests pass" : `\n✗ ${failures} test(s) failed`);
process.exit(failures === 0 ? 0 : 1);
