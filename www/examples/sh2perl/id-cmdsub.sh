#!/usr/bin/env bash
# ============================================================================
# id-cmdsub.sh
# ------------
# Minimal self-contained demo of the GNU coreutils 'id' command.
#
# This script is designed to be safe (no rm -rf, no destructive ops).
# It is used as a test case for the shell-to-Perl translator.
#
# Each section prints debug-like output to show what the command returns.
# ============================================================================

set -u  # treat unset variables as an error
# Don't set -e because we intentionally test failure cases.

RC=0  # cumulative exit code (0 = all tests passed)

# --------------------------------------------------------------------------
# Helper: run a command and capture its stdout, stderr and exit code.
# We use a filesystem-based capture because we're bash and want to be
# compatible even with a simple shell.
# --------------------------------------------------------------------------
capture() {
    local label="$1"
    shift
    local tmp_stdout tmp_stderr
    tmp_stdout=$(mktemp /tmp/id_demo_stdout_XXXXXX)
    tmp_stderr=$(mktemp /tmp/id_demo_stderr_XXXXXX)
    # Run the command, saving both streams.
    "$@" >"$tmp_stdout" 2>"$tmp_stderr"
    local ec=$?
    local so
    so=$(cat "$tmp_stdout")
    local se
    se=$(cat "$tmp_stderr")
    rm -f "$tmp_stdout" "$tmp_stderr"
    echo "--- [${label}] ---"
    echo "  cmd     : $*"
    echo "  exitcode: ${ec}"
    if [[ -n "${so}" ]]; then
        echo "  stdout  : ${so}"
    fi
    if [[ -n "${se}" ]]; then
        echo "  stderr  : ${se}"
    fi
    echo ""
    return ${ec}
}

# ============================================================================
# 1. Default output (no options) — current process
# ============================================================================
echo "============================================================"
echo " SECTION 1: 'id' (default — current process)"
echo "============================================================"
capture "01-default" id

# ============================================================================
# 2. Effective user ID (numeric)
# ============================================================================
echo "============================================================"
echo " SECTION 2: id -u  (effective user ID, numeric)"
echo "============================================================"
capture "02-u" id -u

# ============================================================================
# 3. Effective group ID (numeric)
# ============================================================================
echo "============================================================"
echo " SECTION 3: id -g  (effective group ID, numeric)"
echo "============================================================"
capture "03-g" id -g

# ============================================================================
# 4. All supplementary group IDs (numeric)
# ============================================================================
echo "============================================================"
echo " SECTION 4: id -G  (all group IDs, numeric)"
echo "============================================================"
capture "04-G" id -G

# ============================================================================
# 5. Effective user name  (numeric)
# ============================================================================
echo "============================================================"
echo " SECTION 5: id -un  (effective user name)"
echo "============================================================"
capture "05-un" id -un

# ============================================================================
# 6. Effective group name
# ============================================================================
echo "============================================================"
echo " SECTION 6: id -gn  (effective group name)"
echo "============================================================"
capture "06-gn" id -gn

# ============================================================================
# 7. All supplementary group names
# ============================================================================
echo "============================================================"
echo " SECTION 7: id -Gn  (all group names)"
echo "============================================================"
capture "07-Gn" id -Gn

# ============================================================================
# 8. Real user ID (numeric)    -r  flag
# ============================================================================
echo "============================================================"
echo " SECTION 8: id -ru  (real user ID, numeric)"
echo "============================================================"
capture "08-ru" id -ru

# ============================================================================
# 9. Real group ID (numeric)
# ============================================================================
echo "============================================================"
echo " SECTION 9: id -rg  (real group ID, numeric)"
echo "============================================================"
capture "09-rg" id -rg

# ============================================================================
# 10. Real supplementary group IDs (numeric)
# ============================================================================
echo "============================================================"
echo " SECTION 10: id -rG  (real group IDs, numeric)"
echo "============================================================"
capture "10-rG" id -rG

# ============================================================================
# 11. Real user name
# ============================================================================
echo "============================================================"
echo " SECTION 11: id -run  (real user name)"
echo "============================================================"
capture "11-run" id -run

# ============================================================================
# 12. Real group name
# ============================================================================
echo "============================================================"
echo " SECTION 12: id -rgn  (real group name)"
echo "============================================================"
capture "12-rgn" id -rgn

# ============================================================================
# 13. Real supplementary group names
# ============================================================================
echo "============================================================"
echo " SECTION 13: id -rGn  (real group names)"
echo "============================================================"
capture "13-rGn" id -rGn

# ============================================================================
# 14. Separate long-form options: -u -n  (same as -un)
# ============================================================================
echo "============================================================"
echo " SECTION 14: id -u -n  (separate options, equivalent to -un)"
echo "============================================================"
capture "14-u-n" id -u -n

# ============================================================================
# 15. Separate options: -u -r  (same as -ru)
# ============================================================================
echo "============================================================"
echo " SECTION 15: id -r -u  (separate options, equivalent to -ru)"
echo "============================================================"
capture "15-r-u" id -r -u

# ============================================================================
# 16. Zero-delimited group IDs  (-G -z)
# ============================================================================
echo "============================================================"
echo " SECTION 16: id -G -z  (group IDs delimited by NUL)"
echo "============================================================"
capture "16-Gz" bash -c 'id -G -z | cat -v'

# ============================================================================
# 17. Zero-delimited group names  (-Gn -z)
# ============================================================================
echo "============================================================"
echo " SECTION 17: id -Gn -z  (group names delimited by NUL)"
echo "============================================================"
capture "17-Gnz" bash -c 'id -Gn -z | cat -v'

# ============================================================================
# 18. Zero-delimited user name  (-un -z)
# ============================================================================
echo "============================================================"
echo " SECTION 18: id -un -z  (user name with NUL terminator)"
echo "============================================================"
capture "18-unz" bash -c 'id -un -z | cat -v'

# ============================================================================
# 19. -Z  --context  (SELinux security context — may fail)
# ============================================================================
echo "============================================================"
echo " SECTION 19: id -Z  (security context — may not be available)"
echo "============================================================"
capture "19-Z" id -Z

# ============================================================================
# 20. With a specific user: 'root'
# ============================================================================
echo "============================================================"
echo " SECTION 20: id root  (default output for user 'root')"
echo "============================================================"
capture "20-root" id root

# ============================================================================
# 21. Numeric UID for root
# ============================================================================
echo "============================================================"
echo " SECTION 21: id -u root  (numeric UID of root)"
echo "============================================================"
capture "21-u-root" id -u root

# ============================================================================
# 22. Numeric GID for root
# ============================================================================
echo "============================================================"
echo " SECTION 22: id -g root  (numeric GID of root)"
echo "============================================================"
capture "22-g-root" id -g root

# ============================================================================
# 23. All group IDs (numeric) for root
# ============================================================================
echo "============================================================"
echo " SECTION 23: id -G root  (all group IDs of root, numeric)"
echo "============================================================"
capture "23-G-root" id -G root

# ============================================================================
# 24. User name for root
# ============================================================================
echo "============================================================"
echo " SECTION 24: id -un root  (user name of root)"
echo "============================================================"
capture "24-un-root" id -un root

# ============================================================================
# 25. Real user ID for root (-ru)
# ============================================================================
echo "============================================================"
echo " SECTION 25: id -ru root  (real user ID of root, numeric)"
echo "============================================================"
capture "25-ru-root" id -ru root

# ============================================================================
# 26. id -a  (compatibility flag, ignored)
# ============================================================================
echo "============================================================"
echo " SECTION 26: id -a  (compatibility flag — same as default)"
echo "============================================================"
capture "26-a" id -a

# ============================================================================
# Summary
# ============================================================================
echo ""
echo "All id demo sections completed."
exit ${RC}
